// checkBackupEncryptionKey proves that the configured key source can wrap and
// unwrap a data key (it also exercises the remote permissions of a Key Vault).
func checkBackupEncryptionKey(ctx context.Context, app App) error {
	src, err := backupKeySource(app)
	if err != nil {
		return err
	}

	probe := make([]byte, keys.KEKLength)
	if _, err := rand.Read(probe); err != nil {
		return err
	}

	wrapped, err := src.Wrap(ctx, probe)
	if err != nil {
		return fmt.Errorf("the key source failed to wrap a key: %w", err)
	}

	if _, err := src.Unwrap(ctx, src.KeyID(), wrapped); err != nil {
		return fmt.Errorf("the key source failed to unwrap a key: %w", err)
	}

	return nil
}

// registerBackupEncryptionHooks refuses to enable the backup encryption
// while no working key is configured, instead of failing the first (cron)
// backup at night.
func (app *BaseApp) registerBackupEncryptionHooks() {
	app.OnSettingsUpdateRequest().Bind(&hook.Handler[*SettingsUpdateRequestEvent]{
		Id:       "__clavigerBackupEncryptionCheck__",
		Priority: -100,
		Func: func(e *SettingsUpdateRequestEvent) error {
			if !e.NewSettings.Backups.Encrypt || (e.OldSettings != nil && e.OldSettings.Backups.Encrypt) {
				return e.Next()
			}

			ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
			defer cancel()

			if err := checkBackupEncryptionKey(ctx, e.App); err != nil {
				msg := "Cannot enable backup encryption: " + err.Error()

				return router.NewBadRequestError(msg, validation.Errors{
					"backups": validation.Errors{
						"encrypt": validation.NewError("validation_backup_encryption_key", err.Error()),
					},
				})
			}

			return e.Next()
		},
	})
}
