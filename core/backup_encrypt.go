// Fork-local (Claviger #78): encrypted backups.
//
// An encrypted backup is the usual zip archive run through the chunked
// AES-256-GCM stream of package backupenc, stored as "<name>.zip.enc". It is
// opt-in (Settings.Backups.Encrypt). Plain archives keep working in every
// state of the setting: whether a stored backup is encrypted is decided by its
// leading magic bytes, never by its name or by the current setting.

// BackupEncryptedExt is the file name extension of an encrypted backup.
const BackupEncryptedExt = ".enc"

// IsEncryptedBackupName reports whether the backup name follows the naming
// of encrypted backups. It is only a hint (used by the list and the UI);
// restore and verify check the content.
func IsEncryptedBackupName(name string) bool {
	return strings.HasSuffix(name, BackupEncryptedExt)
}

// BackupStoredName returns the name under which a backup that is created
// with the given name is stored: with backup encryption enabled, ".enc" is
// appended. An empty name stays empty (it is autogenerated later) and the
// name is unchanged when the encryption is off.
func BackupStoredName(app App, name string) string {
	if name == "" || !app.Settings().Backups.Encrypt || IsEncryptedBackupName(name) {
		return name
	}

	return name + BackupEncryptedExt
}

// backupKeySource returns the key source that wraps/unwraps backup keys.
//
// It is the same source as the field encryption one (CLAVIGER_KEK,
// CLAVIGER_KEK_FILE, the Azure Key Vault key or the app encryption key,
// plus the *_OLD variants of a rotation in progress).
func backupKeySource(app App) (keys.KeySource, error) {
	return fieldKeySource(app)
}

// peekBackupEncrypted reports whether the stream starts like an encrypted
// backup, without consuming it.
func peekBackupEncrypted(br *bufio.Reader) bool {
	b, _ := br.Peek(len(backupenc.Magic))
	return backupenc.IsEncrypted(b)
}

// openBackupDecrypted wraps the already magic-checked stream into a
// decrypting reader and turns the key failures into actionable errors.
func openBackupDecrypted(ctx context.Context, app App, br *bufio.Reader) (io.Reader, error) {
	hdr, err := backupenc.ReadHeader(br)
	if err != nil {
		return nil, fmt.Errorf("invalid encrypted backup: %w", err)
	}

	src, err := backupKeySource(app)
	if err != nil {
		return nil, fmt.Errorf("the backup is encrypted (key %s) and cannot be opened: %w", hdr.KeyID, err)
	}

	r, err := backupenc.NewReaderFromHeader(ctx, hdr, br, src)
	if err != nil {
		switch {
		case errors.Is(err, keys.ErrKeyIDMismatch):
			return nil, fmt.Errorf("the backup is encrypted with key %s, which is not available: "+
				"provide it (as %s, %s or %s while the current key stays configured) and try again: %w",
				hdr.KeyID, keys.EnvKEKOld, keys.EnvKEKFileOld, keys.EnvKEKAzureKeyIDOld, err)
		case errors.Is(err, keys.ErrUnwrap):
			return nil, fmt.Errorf("the backup is encrypted with key %s, but that key failed to open it "+
				"(wrong key material, or the backup header was altered): %w", hdr.KeyID, err)
		}
		return nil, fmt.Errorf("failed to open the encrypted backup (key %s): %w", hdr.KeyID, err)
	}

	return r, nil
}

// copyBackupAsZip copies the backup stream into dest and returns true if it
// had to decrypt it. A plain archive is copied byte for byte and never needs
// a key.
func copyBackupAsZip(ctx context.Context, app App, r io.Reader, dest io.Writer) (encrypted bool, err error) {
	br := bufio.NewReaderSize(r, 64*1024)

	if !peekBackupEncrypted(br) {
		_, err = io.Copy(dest, &ctxReader{ctx: ctx, r: br})
		return false, err
	}

	dr, err := openBackupDecrypted(ctx, app, br)
	if err != nil {
		return true, err
	}

	_, err = io.Copy(dest, &ctxReader{ctx: ctx, r: dr})

	return true, err
}

// backupFileIsEncrypted checks the leading bytes of a local backup file.
func backupFileIsEncrypted(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()

	head := make([]byte, len(backupenc.Magic))
	n, _ := io.ReadFull(f, head)

	return backupenc.IsEncrypted(head[:n]), nil
}

// decryptLocalBackupToTemp decrypts the local backup file into a new temp
// file inside dir and returns its path (the caller removes it).
func decryptLocalBackupToTemp(ctx context.Context, app App, path, dir, pattern string) (string, error) {
	src, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer src.Close()

	tmp, err := os.CreateTemp(dir, pattern)
	if err != nil {
		return "", err
	}

	_, err = copyBackupAsZip(ctx, app, src, tmp)
	err = errors.Join(err, tmp.Close())
	if err != nil {
		_ = os.Remove(tmp.Name())
		return "", err
	}

	return tmp.Name(), nil
}

